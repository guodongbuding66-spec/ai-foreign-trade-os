import assert from 'node:assert/strict';
import { documentMediaCapability, normalizeDocumentMediaMime, safeDocumentFileName, sniffDocumentMediaMime, validateDocumentMedia } from '../functions/_lib/document-media.js';
import { mediaProviderSupports, selectMediaProviderId } from '../functions/_lib/ai-media.js';
assert.equal(normalizeDocumentMediaMime('x.PDF',''),'application/pdf');
assert.equal(normalizeDocumentMediaMime('scan.jpg',''),'image/jpeg');
assert.equal(documentMediaCapability('application/pdf'),'pdf');
assert.equal(documentMediaCapability('image/png'),'vision');
assert.equal(validateDocumentMedia({name:'bl.pdf',type:'application/pdf',size:1024}).ok,true);
assert.equal(validateDocumentMedia({name:'malware.exe',type:'application/octet-stream',size:1024}).ok,false);
assert.equal(validateDocumentMedia({name:'huge.pdf',type:'application/pdf',size:9*1024*1024},8*1024*1024).error,'document_file_too_large');
assert.equal(sniffDocumentMediaMime(Uint8Array.from([0x25,0x50,0x44,0x46,0x2d,0x31])),'application/pdf');
assert.equal(sniffDocumentMediaMime(Uint8Array.from([0xff,0xd8,0xff,0xdb])),'image/jpeg');
assert.equal(safeDocumentFileName('../BL:001?.pdf'),'.._BL_001_.pdf');
const env={OPENAI_API_KEY:'sk-test-key',OPENAI_MODEL:'gpt-5',DEEPSEEK_API_KEY:'ds-test-key',DEEPSEEK_MODEL:'deepseek-chat',AI_DEFAULT_PROVIDER:'deepseek'};
assert.equal(mediaProviderSupports(env,'openai','application/pdf'),true);
assert.equal(mediaProviderSupports(env,'deepseek','application/pdf'),false);
assert.equal(selectMediaProviderId(env,'','application/pdf'),'openai');
assert.throws(()=>selectMediaProviderId(env,'deepseek','application/pdf'),/does not expose pdf input/);
console.log('Document media smoke OK');
