import assert from 'node:assert/strict';
import { amendmentAIInput, buildAmendmentChecklist, deterministicAmendmentDraft, publicAmendmentIssue } from '../functions/_lib/lc-amendment.js';
const row={id:'d1',rule_key:'LC-001',field_path:'letters_of_credit.amount',severity:'Critical',status:'Open',message:'信用证金额与Order不一致。',expected_json:'100000',actual_json:'99000',created_at:'2026-08-19T00:00:00Z'};
const issue=publicAmendmentIssue(row);
assert.equal(issue.expected,100000);
assert.equal(issue.actual,99000);
const checklist=buildAmendmentChecklist({issues:[issue]});
assert.equal(checklist.length,1);
assert.equal(checklist[0].discrepancyId,'d1');
assert.match(checklist[0].requestedChange,/LC-001|amount/);
const draft=deterministicAmendmentDraft({lc:{lc_no:'LC2026001'},order:{order_no:'SO-001'},company:{legal_name:'Buyer Co.'},issues:[issue]});
assert.match(draft.subject,/LC2026001/);
assert.match(draft.subject,/SO-001/);
assert.match(draft.body,/100000/);
assert.match(draft.body,/99000/);
const input=amendmentAIInput({lc:{id:'lc1',lc_no:'LC2026001',amount:99000,currency:'USD'},order:{id:'o1',order_no:'SO-001',amount:100000,currency:'USD'},issues:[issue]});
assert.equal(input.letterOfCredit.lcNo,'LC2026001');
assert.equal(input.issues[0].discrepancyId,'d1');
console.log('L/C amendment smoke OK');
